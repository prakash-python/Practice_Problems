# Set operations practice (Union, Intersection, Difference, Symmetric Difference)

s1 = {1, 2, 3, 4, 5, 6}
s2 = {5, 4, 6, 7, 9, 8}

print("Set 1:", s1)
print("Set 2:", s2)
print("Union:", s1.union(s2))
print("Intersection:", s1 & s2)
print("Difference (s1 - s2):", s1 - s2)
print("Symmetric Difference:", s1 ^ s2)
